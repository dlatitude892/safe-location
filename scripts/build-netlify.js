// Builds the static, tracking-only version of Safe Location for Netlify (or any static host) into dist/.
//
// Netlify can only serve files; it cannot run the Safe Location server. So this build:
//   - copies only the public site files (no server code, tests or settings),
//   - writes a config.js that turns accounts, backup, SOS alerts and Trip Mode off ("coming soon" in the UI),
//   - sends the account pages (/signin, /account, ...) to the landing page, since they need the server,
//   - adds the same security headers the Safe Location server sends.
//
// Run locally with:  node scripts/build-netlify.js     (Netlify runs it automatically, see netlify.toml)
"use strict";

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dist = path.join(root, "dist");

// The public files of the tracking-only site. Pages that need the server are deliberately left out.
const FILES = ["index.html", "welcome.html", "app.js", "style.css", "landing.css", "landing.js", "sw.js"];
const FOLDERS = ["fonts", "brand"];
const SERVER_PAGES = ["/signin", "/signup", "/forgot-password", "/reset-password", "/account", "/emergency", "/trips"];

// Keep in step with CONTENT_SECURITY_POLICY in server/app.js.
const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self' https://unpkg.com",
  "style-src 'self' https://unpkg.com",
  "img-src 'self' data: https://tile.openstreetmap.org https://basemaps.cartocdn.com https://unpkg.com",
  "connect-src 'self' https://nominatim.openstreetmap.org https://unpkg.com",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'"
].join("; ");

function build() {
  fs.rmSync(dist, { recursive: true, force: true });
  fs.mkdirSync(dist, { recursive: true });

  for (const file of FILES) fs.copyFileSync(path.join(root, file), path.join(dist, file));
  for (const folder of FOLDERS) fs.cpSync(path.join(root, folder), path.join(dist, folder), { recursive: true });

  // Site settings. The CARTO key (optional, for the Dark map style) is a browser key, so it may be public;
  // set CARTO_API_KEY in Netlify's environment variables to use it.
  const settings = { sync: false, cartoApiKey: process.env.CARTO_API_KEY || "" };
  fs.writeFileSync(
    path.join(dist, "config.js"),
    "// Generated by scripts/build-netlify.js: tracking-only site (no Safe Location server here).\n" +
      `window.SAFE_LOCATION_CONFIG = ${JSON.stringify(settings, null, 2)};\n`
  );

  fs.writeFileSync(
    path.join(dist, "_redirects"),
    "# Generated by scripts/build-netlify.js\n" +
      "/welcome  /welcome.html  200\n" +
      SERVER_PAGES.map((page) => `${page}  /welcome  302`).join("\n") +
      "\n"
  );

  fs.writeFileSync(
    path.join(dist, "_headers"),
    "# Generated by scripts/build-netlify.js (the same headers the Safe Location server sends)\n" +
      "/*\n" +
      "  X-Content-Type-Options: nosniff\n" +
      "  X-Frame-Options: DENY\n" +
      "  Referrer-Policy: strict-origin-when-cross-origin\n" +
      "  Permissions-Policy: geolocation=(self), camera=(), microphone=()\n" +
      `  Content-Security-Policy: ${CONTENT_SECURITY_POLICY}\n` +
      "/fonts/*\n" +
      "  Cache-Control: public, max-age=2592000\n"
  );

  return fs.readdirSync(dist);
}

if (require.main === module) {
  console.log(`Built the tracking-only site into dist/: ${build().join(", ")}`);
}

module.exports = { build, SERVER_PAGES, CONTENT_SECURITY_POLICY };
